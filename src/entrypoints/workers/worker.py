from src.infrastructure.openai import OpenAIClient
from src.infrastructure.trading_view import TradingView
from src.service.queries import CandleQueries, IndicatorQueries, LevelQueries


class ForecastWorker: 
    def __init__(self) -> str: 
        self.openai_client = OpenAIClient()

    def make_a_forecast(self, ticker: str) -> None:
        # Get charts 
        with TradingView() as trading_view:
            trading_view.get_ticker_chart(ticker) 

        # Get candles + indicators
        candles_5m, candles_15m, candles_1h, candles_4h, candles_1d, candles_1w = CandleQueries.get_candles_by_ticker(ticker)
        indicators_5m = IndicatorQueries.get_candle_indicators(candles_5m)
        indicators_15m = IndicatorQueries.get_candle_indicators(candles_15m)
        indicators_1h = IndicatorQueries.get_candle_indicators(candles_1h)
        indicators_4h = IndicatorQueries.get_candle_indicators(candles_4h)
        indicators_1d = IndicatorQueries.get_candle_indicators(candles_1d)
        indicators_1w = IndicatorQueries.get_candle_indicators(candles_1w)
        levels = LevelQueries.get_levels_by_ticker(ticker)

        prompt = f"""
        **Примечание:** Анализ предназначен исключительно для образовательных целей. Используй точные цифры в торгов плане и давай максимально точный процент успеха. Все цифры которые были указаны для примера не используются для анализа, а лишь являются примером.
        Провести исчерпывающий мульти-таймфрейм анализ для тикера {ticker} с целью разработки долгосрочной торговой стратегии с потенциальным ROI > 50%. Timeframes: 5m, 15m, 1h, 4h, 1d, 1w.

        **1. Контекст Рынка и Исходные Данные:**

        * **Старшие Таймфреймы (для определения глобального тренда):**
            * Данные по последним свечам (Weekly, Daily):
                * Последнии свечи 1d: {candles_1d[-200:] if len(candles_1d) > 200 else candles_1d}
                * Последнии свечи 1w: {candles_1w[-200:] if len(candles_1w) > 200 else candles_1w}
            * Ключевые индикаторы (Weekly, Daily):
                * Последнии индикаторы 1d: {indicators_1d}
                * Последнии индикаторы 1w: {indicators_1w}

        * **Младшие Таймфреймы (для поиска точки входа):**
            * Данные по последним свечам (4h, 1h, 5m, 15m):
                * Последнии свечи 5m: {candles_5m[-200:] if len(candles_5m) > 200 else candles_5m}
                * Последнии свечи 15m: {candles_15m[-200:] if len(candles_15m) > 200 else candles_15m}
                * Последнии свечи 1h: {candles_1h[-200:] if len(candles_1h) > 200 else candles_1h}
                * Последнии свечи 4h: {candles_4h[-200:] if len(candles_4h) > 200 else candles_4h}
            * Ключевые индикаторы (4h, 1h, 5m, 15m):
                * Последнии индикаторы 5m: {indicators_5m}
                * Последнии индикаторы 15m: {indicators_15m}
                * Последнии индикаторы 1h: {indicators_1h}
                * Последнии индикаторы 4h: {indicators_4h}

        * **Ключевые Уровни:**
            * Глобальные уровни (исторические максимумы/минимумы, сильные зоны поддержки/сопротивления с недельного и дневного графиков): {levels}

        **2. Задачи для Анализа:**

        **I. Макро-анализ (Таймфреймы 1W, 1D):**
            * Определение тренда: Опиши глобальный тренд (восходящий/нисходящий/боковик), используя теорию Эллиотта или структуру рынка (последовательность HH/HL или LL/LH).
            * Ключевые паттерны: Идентифицируй и опиши наиболее значимые долгосрочные графические паттерны (например, "Голова и плечи", "Двойное дно", "Клин", "Канал накопления/распределения по Вайкоффу").
            * Анализ индикаторов: Проанализируй индикаторы. Есть ли бычьи/медвежьи дивергенции? Находятся ли индикаторы в экстремальных зонах? Как цена взаимодействует с долгосрочными скользящими средними (EMA 50/200)?

        **II. Тактический анализ (Таймфреймы 4h, 1h):**
            * Локальная структура: Опиши текущую структуру рынка внутри глобального тренда. Происходит ли коррекция, импульс или консолидация?
            * Анализ конфлюэнтности: Найди точки, где несколько аналитических инструментов дают одинаковый сигнал. Например:
                * Цена находится на уровне поддержки 0.618 по Фибоначчи.
                * Этот же уровень совпадает с EMA(200) на 4h графике.
                * На RSI наблюдается скрытая бычья дивергенция.
                * Наблюдается повышенный объем на подходе к этому уровню.

        **III. Поиск Точки Входа (15m, 5m):**
            * Подтверди локальную структуру. Найди слом структуры (BOS/CHoCH) на младшем ТФ, который сигнализирует о готовности цены двигаться в направлении основного сетапа.
            * Определи точный паттерн для входа (например, "пин-бар на уровне", "поглощение", "микро-слом структуры с ретестом").

        **IV. Торговый План (с максимальной точностью цен):**
            * **Направление:** Лонг или Шорт.
            * **Зона для входа:** Укажи узкий диапазон цен для набора позиции (например, $145.55 - $148.25). Обоснуй, почему именно эта зона (например, "ордер-блок на 1h + зона 0.5 по Фибоначчи").
            * **Стоп-лосс:** Установи точный ценовой уровень (например, $139.87).
            * **Обоснование стоп-лосса и точка инвалидации**: Объясни, почему стоп-лосс находится именно здесь. Какое ценовое действие полностью отменит торговую идею? (например, "Стоп за локальным минимумом и ниже зоны ликвидности. Закрепление цены ниже этого уровня отменяет бычий сценарий").
            * **Тейк-профит:** Укажи точные ценовые уровни для 3 целей (TP1, TP2, TP3) с потенциалом на долгосрок.
            * **Обоснование целей:** Объясни выбор каждой цели (например, "TP1: ближайший сильный уровень сопротивления на 4h. TP2: Point of Control глобального диапазона. TP3: уровень -0.618 по Фибоначчи от глобального движения").
            * **Соотношение Риск/Прибыль (R/R):** Рассчитай R/R для каждой цели (минимально приемлемое 1 к 3).
        
        **V. Управление Риском и Капиталом:**
            * **Плечо и Тип торговли:** Обоснуй выбор (спот или фьючерсы с плечом 1x-5x) для долгосрочной стратегии.
            * **Размер позиции:** Опиши, как рассчитать размер позиции исходя из правила риска (1-2% от депозита).
            * **План управления позицией:** 
                * **При достижении TP1**: Перевести стоп-лосс в безубыток и зафиксировать 30-50% позиции.
                * **При достижении TP2**: Переместить стоп-лосс под уровень TP1 (трейлинг-стоп) и зафиксировать еще 30% позиции.
                * **Оставшаяся часть**: Держать до TP3 или до появления сигналов разворота на старших ТФ.

        **VI. Сводный анализ и Вероятность:**
            * Резюме: В 2-3 предложениях изложи суть торговой идеи, объединив выводы со всех таймфреймов.
            * Оцени вероятность успеха предложенного торгового плана в процентах.
            * Факторы "ЗА" (усиливающие сетап):
                * [Пример: Глобальный тренд восходящий]
                * [Пример: Наличие бычьей дивергенции на дневном графике]
                * [Пример: Цена находится в сильной зоне поддержки]
            * Факторы "ПРОТИВ" (риски и ослабляющие факторы):
                * [Пример: Общий рыночный сентимент негативный]
                * [Пример: На 4h графике формируется медвежий паттерн "голова и плечи"]
                * [Пример: Низкие объемы торгов, указывающие на слабый интерес покупателей]

        **Примечание:** Анализ предназначен исключительно для образовательных целей. Используй точные цифры в торгов плане и давай максимально точный процент успеха. Все цифры которые были указаны для примера не используются для анализа, а лишь являются примером.
        **Язык:** Отвечай на русском.

        **ФОРМАТ ВЫВОДА: Telegram-сообщение (твой итоговый ответ) Тут только результаты которые ты посчитал без лишней информации.**
        **Ничего больше не добавляй кроме полей указаных ниже. Так же не нужно добавлять свою аргументацию в ответ. Только результаты.**
        **Точный ценовой уровень (например, $139.87)**
            🟢 **LONG СЕТАП: {ticker}** 📈
            (Или 🔴 SHORT СЕТАП)

            **📋 Торговый план**:
                • Зона входа: **цена_входа_1** - **цена_входа_2**
                • Стоп-лосс: **цена_стоп_лосса**
                • Тайм-фрейм: **оптимальный тайм-фрейм**
                • Плечо: **оптимальное плечо для торговли**

            **🎯 Тейк-профит**:
                • **цель_1** (R/R: RR1)
                • **цель_2** (R/R: RR2)
                • **цель_3** (R/R: RR3)

            **⚖️ Оценка уверенности: процент успеха**
        """
        return self.openai_client.create_response(prompt)
